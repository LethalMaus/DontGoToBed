#!/usr/bin/env python3
"""Validate the reviewable UTF-8 translation table and generate shared Kotlin data."""
from pathlib import Path
import csv,json,re
ROOT=Path(__file__).resolve().parents[1]
rows=list(csv.reader((ROOT/'docs/localization/translations.tsv').open(),delimiter='\t'))[1:]
seen=set()
for row in rows:
 assert len(row)==7, (len(row),row[:1])
 assert row[0] not in seen, row[0]
 seen.add(row[0])
 for value in row:
  assert value.strip(),row[0]
  assert sorted(re.findall(r'\{\d+\}',value))==sorted(re.findall(r'\{\d+\}',row[0])),row[0]
def kt(s):return json.dumps(s.replace('\\n','\n'),ensure_ascii=False).replace('$','\\$')
out=['package dev.jamescullimore.dontgotobed','', '// Generated by scripts/generate-localization.py; edit docs/localization/translations.tsv.','internal val translations: Map<String, List<String>> = mapOf(']
out += ['    '+kt(r[0])+' to listOf('+', '.join(kt(x) for x in r[1:])+'),' for r in rows]
out += [')','']
(ROOT/'composeApp/src/commonMain/kotlin/dev/jamescullimore/dontgotobed/Translations.kt').write_text('\n'.join(out))
print(f'Validated {len(rows)} messages × 6 languages; placeholders match.')
